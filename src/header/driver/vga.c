static uint8_t get_font_line(char c, int line) {
    if (line < 0 || line >= 16) return 0;
    uint8_t u = (uint8_t) c;

    // ================= Karakter Grafis Blok & Shade CP437 =================
    if (u == 0xDB) return 0xFF;                          // █ Full block
    if (u == 0xDF) return (line < 8)  ? 0xFF : 0x00;     // ▀ Upper half
    if (u == 0xDC) return (line >= 8) ? 0xFF : 0x00;     // ▄ Lower half
    if (u == 0xDD) return 0xF0;                          // ▌ Left half
    if (u == 0xDE) return 0x0F;                          // ▐ Right half
    if (u == 0xB0) return (line & 1) ? 0x00 : 0x55;      // ░ Light shade (25%)
    if (u == 0xB1) return (line & 1) ? 0x55 : 0xAA;      // ▒ Medium shade (50%)
    if (u == 0xB2) return (line & 1) ? 0x77 : 0xDD;      // ▓ Dark shade (75%)
    if (u == 0x11) {                                     // ◄ Left pointer
        static const uint8_t lptr[16] = {
            0, 0, 0, 0, 0x08, 0x18, 0x38, 0x78, 0x78, 0x38, 0x18, 0x08, 0, 0, 0, 0
        };
        return lptr[line];
    }
    if (u == 0x10) {                                     // ► Right pointer
        static const uint8_t rptr[16] = {
            0, 0, 0, 0, 0x10, 0x18, 0x1C, 0x1E, 0x1E, 0x1C, 0x18, 0x10, 0, 0, 0, 0
        };
        return rptr[line];
    }

    if (u < 32 || u > 126) return 0;
    return font_8x16[u - 32][line];
}

// ==================== 3. INISIALISASI MODE ====================

void vga_init_graphics_mode(void) {
    out(0x3C2, 0xE3);

    for (uint8_t i = 0; i < 5; i++) {
        out(0x3C4, i);
        out(0x3C5, vga_mode12_seq[i]);
    }

    out(0x3D4, 0x11);
    out(0x3D5, in(0x3D5) & 0x7F);

    for (uint8_t i = 0; i < 25; i++) {
        out(0x3D4, i);
        out(0x3D5, vga_mode12_crtc[i]);
    }

    for (uint8_t i = 0; i < 9; i++) {
        out(0x3CE, i);
        out(0x3CF, vga_mode12_gc[i]);
    }

    for (uint8_t i = 0; i < 21; i++) {
        in(0x3DA);
        out(0x3C0, i);
        out(0x3C0, vga_mode12_ac[i]);
    }
    in(0x3DA);
    out(0x3C0, 0x20);

    in_graphics_mode = true;
    vga_clear_screen(VGA_COLOR_BLACK);
}

void vga_init_text_mode(void) {
    in_graphics_mode = false;
}

bool vga_is_graphics_mode(void) {
    return in_graphics_mode;
}

// ==================== 4. PRIMITIF GRAFIK (PER-PIXEL) ====================

void vga_put_pixel(int x, int y, uint8_t color) {
    if (x < 0 || x >= VGA_WIDTH || y < 0 || y >= VGA_HEIGHT) return;

    uint16_t offset = y * (VGA_WIDTH / 8) + (x >> 3);
    uint8_t bit_mask = 0x80 >> (x & 7);
    volatile uint8_t *vram = VGA_VRAM + offset;

    out(0x3CE, 0x08);
    out(0x3CF, bit_mask);

    volatile uint8_t dummy = *vram;
    (void) dummy;

    *vram = color;
}

void vga_draw_line(int x0, int y0, int x1, int y1, uint8_t color) {
    int dx = (x1 > x0) ? (x1 - x0) : (x0 - x1);
    int dy = (y1 > y0) ? (y1 - y0) : (y0 - y1);
    int sx = (x0 < x1) ? 1 : -1;
    int sy = (y0 < y1) ? 1 : -1;
    int err = dx - dy;

    while (true) {
        vga_put_pixel(x0, y0, color);
        if (x0 == x1 && y0 == y1) break;
        int e2 = 2 * err;
        if (e2 > -dy) {
            err -= dy;
            x0 += sx;
        }
        if (e2 < dx) {
            err += dx;
            y0 += sy;
        }
    }
}

void vga_draw_rect(int x, int y, int w, int h, uint8_t color, bool fill) {
    if (fill) {
        for (int r = y; r < y + h; r++) {
            for (int c = x; c < x + w; c++) {
                vga_put_pixel(c, r, color);
            }
        }
    } else {
        vga_draw_line(x, y, x + w - 1, y, color);
        vga_draw_line(x, y + h - 1, x + w - 1, y + h - 1, color);
        vga_draw_line(x, y, x, y + h - 1, color);
        vga_draw_line(x + w - 1, y, x + w - 1, y + h - 1, color);
    }
}

void vga_draw_circle(int xc, int yc, int r, uint8_t color) {
    int x = 0;
    int y = r;
    int d = 3 - 2 * r;
    while (y >= x) {
        vga_put_pixel(xc + x, yc + y, color);
        vga_put_pixel(xc - x, yc + y, color);
        vga_put_pixel(xc + x, yc - y, color);
        vga_put_pixel(xc - x, yc - y, color);
        vga_put_pixel(xc + y, yc + x, color);
        vga_put_pixel(xc - y, yc + x, color);
        vga_put_pixel(xc + y, yc - x, color);
        vga_put_pixel(xc - y, yc - x, color);
        x++;
        if (d > 0) {
            y--;
            d = d + 4 * (x - y) + 10;
        } else {
            d = d + 4 * x + 6;
        }
    }
}

// ==================== 5. TEXT CONSOLE & KURSOR ====================

void vga_clear_screen(uint8_t color) {
    out(0x3CE, 0x08);
    out(0x3CF, 0xFF);

    for (uint32_t i = 0; i < (VGA_WIDTH / 8) * VGA_HEIGHT; i++) {
        volatile uint8_t dummy = VGA_VRAM[i];
        (void) dummy;
        VGA_VRAM[i] = color;
    }

    memset(text_screen, ' ', sizeof(text_screen));
    memset(text_fg_buf, 0x07, sizeof(text_fg_buf));
    memset(text_bg_buf, color, sizeof(text_bg_buf));
}

void vga_draw_char(int col, int row, char c, uint8_t fg, uint8_t bg) {
    if (col < 0 || col >= VGA_TEXT_COLS || row < 0 || row >= VGA_TEXT_ROWS) return;

    text_screen[row][col] = c;
    text_fg_buf[row][col] = fg;
    text_bg_buf[row][col] = bg;

    for (int l = 0; l < 16; l++) {
        uint8_t glyph = get_font_line(c, l);
        uint16_t offset = (row * 16 + l) * (VGA_WIDTH / 8) + col;
        volatile uint8_t *vram = VGA_VRAM + offset;

        // Background
        out(0x3CE, 0x08);
        out(0x3CF, ~glyph);
        volatile uint8_t dummy1 = *vram;
        (void) dummy1;
        *vram = bg;

        // Foreground
        out(0x3CE, 0x08);
        out(0x3CF, glyph);
        volatile uint8_t dummy2 = *vram;
        (void) dummy2;
        *vram = fg;
    }
}

void vga_set_cursor(int row, int col) {
    if (!in_graphics_mode) return;

    // 1. Kembalikan/gambar ulang karakter asli di posisi kursor lama (tidak ditimpa hitam buta!)
    if (cur_cursor_col >= 0 && cur_cursor_col < VGA_TEXT_COLS &&
        cur_cursor_row >= 0 && cur_cursor_row < VGA_TEXT_ROWS) {
        char old_c = text_screen[cur_cursor_row][cur_cursor_col];
        uint8_t old_fg = text_fg_buf[cur_cursor_row][cur_cursor_col];
        uint8_t old_bg = text_bg_buf[cur_cursor_row][cur_cursor_col];
        if (old_c == 0) old_c = ' ';

        for (int l = 14; l < 16; l++) {
            uint8_t glyph = get_font_line(old_c, l);
            uint16_t offset = (cur_cursor_row * 16 + l) * (VGA_WIDTH / 8) + cur_cursor_col;
            volatile uint8_t *vram = VGA_VRAM + offset;

            out(0x3CE, 0x08);
            out(0x3CF, ~glyph);
            volatile uint8_t dummy1 = *vram; (void) dummy1;
            *vram = old_bg;

            out(0x3CE, 0x08);
            out(0x3CF, glyph);
            volatile uint8_t dummy2 = *vram; (void) dummy2;
            *vram = old_fg;
        }
    }

    cur_cursor_row = row;
    cur_cursor_col = col;

    // 2. Gambar kursor underline putih di posisi baru (scanline 14-15)
    if (cur_cursor_col >= 0 && cur_cursor_col < VGA_TEXT_COLS &&
        cur_cursor_row >= 0 && cur_cursor_row < VGA_TEXT_ROWS) {
        for (int l = 14; l < 16; l++) {
            uint16_t offset = (cur_cursor_row * 16 + l) * (VGA_WIDTH / 8) + cur_cursor_col;
            out(0x3CE, 0x08);
            out(0x3CF, 0xFF);
            volatile uint8_t dummy = VGA_VRAM[offset]; (void) dummy;
            VGA_VRAM[offset] = VGA_COLOR_WHITE;
        }
    }
}

void vga_scroll(void) {
    out(0x3CE, 0x05);
    out(0x3CF, 0x01); // Write Mode 1 (latch copy 4 plane sekaligus)

    uint32_t line_bytes = VGA_WIDTH / 8;
    for (uint32_t i = 0; i < (VGA_HEIGHT - 16) * line_bytes; i++) {
        uint8_t dummy = VGA_VRAM[i + 16 * line_bytes];
        VGA_VRAM[i] = dummy;
    }

    out(0x3CE, 0x05);
    out(0x3CF, 0x02); // Kembalikan ke Write Mode 2

    out(0x3CE, 0x08);
    out(0x3CF, 0xFF);
    for (uint32_t i = (VGA_HEIGHT - 16) * line_bytes; i < VGA_HEIGHT * line_bytes; i++) {
        volatile uint8_t dummy = VGA_VRAM[i];
        (void) dummy;
        VGA_VRAM[i] = VGA_COLOR_BLACK;
    }

    memmove(text_screen[0], text_screen[1], (VGA_TEXT_ROWS - 1) * VGA_TEXT_COLS);
    memmove(text_fg_buf[0], text_fg_buf[1], (VGA_TEXT_ROWS - 1) * VGA_TEXT_COLS);
    memmove(text_bg_buf[0], text_bg_buf[1], (VGA_TEXT_ROWS - 1) * VGA_TEXT_COLS);
    memset(text_screen[VGA_TEXT_ROWS - 1], ' ', VGA_TEXT_COLS);
    memset(text_fg_buf[VGA_TEXT_ROWS - 1], 0x07, VGA_TEXT_COLS);
    memset(text_bg_buf[VGA_TEXT_ROWS - 1], 0x00, VGA_TEXT_COLS);
}